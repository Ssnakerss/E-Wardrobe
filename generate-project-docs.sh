Статус: baseline v0.1  
Нормативный HTTP-контракт: docs/openapi.yaml

## 1. Цели

Протокол должен обеспечивать:

- Полноценное создание и редактирование без сети.
- Сохранность локальных изменений после перезапуска.
- Идемпотентную повторную отправку.
- Инкрементальное получение серверных изменений.
- Явное обнаружение конфликтов.
- Синхронизацию изменений, сделанных через веб.
- Независимую доставку фотографий.
- Изоляцию данных разных пользователей.

Протокол не обещает мгновенную фоновую доставку и автоматическое слияние любых конфликтов.

## 2. Основные понятия

- mutation — локальное намерение изменить сущность.
- mutation_id — UUID, постоянный для всех повторов этой mutation.
- entity_id — UUID категории, вещи или фотографии.
- version — серверная версия конкретной сущности.
- base_version — версия, на основе которой клиент выполнил изменение.
- seq — монотонный номер изменения в пределах пользователя.
- last_pulled_seq — последний полностью применённый клиентом seq.
- outbox — локальная очередь mutations.
- tombstone — запись об удалении сущности.
- snapshot — полное серверное представление сущности.

Время клиента не определяет порядок и не используется для разрешения конфликтов.

## 3. Версии

Для новой серверной сущности version равна 1.

При каждом принятом create/update/delete:

- Сущность получает новую версию.
- Пользователь получает следующий seq.
- В журнал добавляется одна запись.

Create от клиента использует base_version = 0. Update и delete используют последнюю известную клиенту серверную версию.

last_pulled_seq не является version сущности. Это независимые значения.

## 4. Локальная модель SQLite

Минимальные таблицы:

    local_categories
    local_items
    local_photos
    outbox
    photo_upload_queue
    sync_metadata
    sync_conflicts
    deferred_remote_changes

В локальных таблицах сущностей дополнительно хранятся:

- user_id.
- base_version.
- sync_state: clean, pending или conflict.
- server_snapshot_json для сравнения.
- local_created_at и local_updated_at.
- deleted locally marker, если требуется до подтверждения.

sync_metadata содержит как минимум:

- user_id.
- last_pulled_seq.
- last_successful_sync_at.
- installation_id.

Все ключи и запросы должны быть разделены по user_id. Данные другого аккаунта на том же устройстве не смешиваются.

## 5. Локальные операции

### Создание

В одной SQLite-транзакции:

1. Сгенерировать UUID сущности.
2. Вставить локальную сущность.
3. Установить sync_state = pending.
4. Добавить create mutation в outbox.
5. Зафиксировать транзакцию.

### Обновление

В одной транзакции:

1. Обновить локальные поля.
2. Сохранить исходный server snapshot.
3. Добавить update mutation с изменёнными полями.
4. Установить pending.
5. Зафиксировать транзакцию.

### Удаление

- Если сущность ни разу не отправлялась, create и delete могут быть полностью удалены из outbox.
- Если серверная версия существует, добавляется delete mutation.
- Локально сущность скрывается сразу, но физически не удаляется до подтверждения.

### Фотография

Файл копируется из временного picker-каталога в постоянный каталог приложения до того, как операция считается успешно сохранённой. Metadata и ссылка на файл создаются атомарно с outbox-записями.

## 6. Compaction outbox

Перед отправкой клиент объединяет операции, чтобы старые base_version не создавали искусственные конфликты.

Правила:

- create + один или несколько update = один create с последним snapshot.
- update + update = один update с объединённым набором полей и исходной base_version.
- update + delete = один delete с исходной base_version.
- create + delete = локальная отмена, если create ещё не принят сервером.
- Несинхронизированная сущность не должна получать несколько независимых create.

После подтверждения mutation удаляется только подтверждённая часть очереди. Более новые локальные изменения сохраняются.


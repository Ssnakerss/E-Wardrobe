### Шаг 4. Серверная основа синхронизации

Задачи:

- Вести version для категорий, вещей и фотографий.
- Вести per-user sync sequence.
- Записывать полные snapshots в sync_changes.
- Реализовать идемпотентный push.
- Реализовать pull с пагинацией.
- Проверять base_version.
- Возвращать conflict вместе с актуальным snapshot.
- Пропускать веб CRUD через тот же domain service.

Тесты:

- Повтор mutation_id возвращает сохранённый результат.

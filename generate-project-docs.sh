### Стоимость

Стоимость хранится в целых основных единицах валюты:

- 12990 и RUB означают 12990 рублей.
- 120 и USD означают 120 долларов.
- Дробная часть не поддерживается.
- Копейки, центы и другие минорные единицы не хранятся.
- Отрицательные значения запрещены.
- Цена и валюта либо заполнены вместе, либо обе отсутствуют.
- По умолчанию интерфейс предлагает RUB.
- Начальный список выбора: RUB, USD, EUR, KZT, CNY.
- Пересчёт курсов и суммарная стоимость гардероба в одной валюте не реализуются.

В JSON цена передаётся строкой:

    {
      "purchase_price": "12990",
      "price_currency": "RUB"
    }

Это исключает проблемы с 64-битными целыми и числами JavaScript.

### Место хранения

Хранится как текст, а не как отдельный справочник.

Примеры:

- Дома, спальня, верхняя полка.
- Дача, гардероб.
- Кладовка, коробка «Зимняя обувь».

При сохранении обрезаются внешние пробелы и схлопываются повторные пробелы. Пустая строка превращается в NULL.

Мобильные подсказки строятся по локальным вещам и работают офлайн. Веб получает подсказки через отдельный endpoint. Подсказки доступны только в пределах текущего пользователя.

## 8. Фотографии

Требования MVP:

- Несколько фотографий на одну вещь, начальный лимит — 10.
- Камера и галерея на мобильном устройстве.
- Загрузка файла в веб-клиенте.
- Порядок фотографий и выбор обложки через первое фото в списке.
- Миниатюра для списков и полноразмерное изображение для карточки.
- Локальный файл доступен на телефоне сразу после добавления.
- Карточка вещи не зависит от успешной загрузки фотографии.

Обработка:

- Мобильное приложение нормализует изображение в JPEG.
- Учитывается EXIF-ориентация.
- Большая сторона уменьшается максимум до 2560 пикселей.
- EXIF с геолокацией не отправляется.
- Backend проверяет размер, формат и фактическое содержимое.
- Предельный размер исходного upload в MVP — 12 MiB.
- Backend создаёт миниатюру с большей стороной около 512 пикселей.
- Пользовательское имя файла не используется как ключ хранения.
- Декодирование изображений имеет ограничение по размерам и памяти.

Состояния фотографии:

- local_only — существует только на устройстве.
- awaiting_upload — metadata принята сервером, файл ещё не загружен.
- uploading — идёт передача содержимого.
- processing — сервер создаёт миниатюру.
- ready — файл и миниатюра готовы.
- failed — ошибка, доступен повтор.


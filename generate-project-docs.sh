## 10. Offline-first

Мобильный UI читает и изменяет только SQLite. Экраны не зависят от прямого ответа REST API.

Гарантии:

- Создание и редактирование работают без сети.
- Фотографии сохраняются в постоянном каталоге приложения.
- Данные и outbox записываются атомарно.
- Закрытие или перезапуск приложения не удаляет очередь.
- Повтор mutation не создаёт дубликаты.
- Конфликт не приводит к молчаливой потере локальной версии.
- Ошибка одной операции не останавливает независимые операции.
- Выход из аккаунта предупреждает о несинхронизированных данных.

Синхронизация запускается:

- При открытии приложения.
- При возвращении в foreground.
- После локального изменения при наличии сети.
- После восстановления соединения.
- Вручную.
- В фоне только как best effort.

Гарантированная доставка изменений после сворачивания приложения не обещается.

Подробный протокол описан в docs/sync.md.


## 8. Обработка mutation на сервере

Для каждой mutation:

1. Проверить аутентификацию и базовую схему.
2. В транзакции заблокировать user_sync_state пользователя.
3. Найти processed_mutations по user_id и mutation_id.
4. Если запись существует:
   - Сравнить request_hash.
   - При совпадении вернуть сохранённый результат.
   - При различии вернуть mutation_id_reused.
5. Проверить владельца и существование entity_id.
6. Проверить зависимость от категории или вещи.
7. Проверить base_version.
8. Применить доменную валидацию.
9. Обновить сущность и её version.
10. Увеличить seq.
11. Записать sync_changes.
12. Сохранить mutation_id, request_hash и результат.
13. Зафиксировать транзакцию.

Результаты:

- applied — изменение принято.
- duplicate — mutation уже обрабатывалась с тем же содержимым.
- conflict — сущность изменилась относительно base_version.
- validation_error — операция нарушает доменные правила.
- dependency_missing — зависимость ещё не доступна.
- mutation_id_reused — один ID использован для разных запросов.

Ошибка валидации не откатывает другие независимые mutations пакета. Каждая mutation имеет собственную транзакцию.

## 9. Повторная доставка

Клиент не меняет mutation_id после:

- Таймаута.
- Обрыва соединения.
- Перезапуска приложения.
- HTTP 500.
- Отсутствия ответа после фактической серверной обработки.

HTTP 401 не означает потерю данных. Outbox остаётся, а синхронизация приостанавливается до повторного входа.

Постоянные ошибки валидации требуют действия пользователя или исправления зависимости. Они не должны вызывать бесконечный быстрый retry.

## 10. Pull

Запрос:

    GET /api/v1/sync/pull?since=42&limit=200

Ответ содержит:

- Изменения в порядке возрастания seq.
- Полный payload для upsert.
- Tombstone для delete.
- next_since.
- has_more.

Клиент продолжает запросы, пока has_more не станет false.

Применение страницы:

1. Начать SQLite-транзакцию.
2. Для каждого clean entity применить snapshot или tombstone.
3. Для pending/conflict entity не перезаписывать локальные данные.
4. Сохранить remote snapshot в deferred_remote_changes или sync_conflicts.
5. Обновить last_pulled_seq до последней обработанной записи.
6. Зафиксировать транзакцию.

last_pulled_seq нельзя обновлять раньше сохранения изменений или deferred-записи.

## 11. Полный цикл

Базовый цикл:

1. Получить single-flight блокировку Sync Engine.
2. Проверить, что локальные миграции завершены.
3. Выполнить pull для уменьшения вероятности конфликтов.
4. Выполнить compact outbox.
5. Отправить доступные push batches.
6. Обработать acknowledgements и конфликты.
7. Повторить pull для получения собственных и параллельных серверных изменений.
8. Запустить доступные photo uploads.
9. Обновить last_successful_sync_at только после завершения применимых шагов.

Наличие конфликта не делает весь цикл неуспешным. Чистые сущности продолжают синхронизироваться.

## 12. Конфликты

### Update versus update

Сервер возвращает:

- Текущую версию.
- Текущий snapshot.
- Исходную mutation можно сохранить локально для повторного анализа.

Пользователь выбирает:

- Взять серверную версию: локальная версия заменяется после явного подтверждения.
- Оставить свою: создаётся новая mutation с актуальной base_version и полным набором полей, которые пользователь решил сохранить.

Повторное использование старой mutation запрещено.

### Update versus delete

Локальное обновление не воскрешает удалённую сущность автоматически.

Варианты:

- Принять удаление.
- Создать новую вещь с новым UUID на основе локальной копии.

### Delete versus delete

Считается успешным идемпотентным результатом, если запись уже удалена тем же пользователем и правила владельца соблюдены.

### Create с существующим entity_id

Если это не повтор той же mutation, возвращается конфликт идентификатора. Автоматическое перезаписывание запрещено.

### Категории

Дополнительно проверяются:

- Циклы.
- Отсутствие родителя.
- Использование категории вещами.
- Удаление родителя при наличии дочерних записей.

## 13. Синхронизация фотографий

Metadata и содержимое передаются раздельно.

Создание:

1. Push создаёт item, если он ещё не существует.
2. Push создаёт photo metadata с заранее созданным UUID.
3. Сервер сохраняет photo в awaiting_upload.
4. Content queue отправляет PUT content.
5. Сервер проверяет и обрабатывает файл.
6. После перехода в ready сервер публикует photo upsert в sync journal.

Пока фотография не готова, другие устройства могут не показывать её metadata. Карточка вещи при этом уже синхронизируется.

Повтор upload:

- Используется тот же photo_id.
- Если сервер уже имеет ready-файл, повтор возвращает успешный результат после проверки владельца.
- Клиент может повторно отправить файл целиком.
- Resumable/chunked upload не входит в MVP.

Скачивание:

- Клиент сначала запрашивает thumbnail.
- Original загружается по необходимости.
- Ошибка скачивания не меняет доменную карточку.
- Локальный оригинал не удаляется, пока существуют незавершённые операции.

## 14. Зависимости и частичные ошибки

Если вещь ссылается на категорию, которая ещё не дошла до сервера:

- Сервер возвращает dependency_missing.
- Клиент оставляет вещь в outbox.
- Другие независимые вещи продолжают отправляться.
- После подтверждения категории вещь отправляется повторно.

Очередь не должна навсегда блокироваться первой записью. В то же время порядок операций над одной сущностью сохраняется.

## 15. Журнал и retention

В MVP:

- sync_changes сохраняются без автоматической очистки.
- Tombstones сохраняются.
- processed_mutations сохраняются.
- Новый клиент может начать с since=0 и применить историю.
- При небольших объёмах это приемлемо и упрощает корректность.

До реализации compaction нельзя удалять старые записи по одному только возрасту: устройство может вернуться спустя месяцы.

Будущая оптимизация:

- Зарегистрированные devices и их sync cursors.
- Snapshot + журнал после snapshot.
- Очистка истории только после учёта активных устройств.
- Процедура full resync для отставших устройств.

## 16. Retry и сеть

- Сетевые ошибки: exponential backoff с jitter.
- 429: учитывать Retry-After.
- 401: остановить server sync, локальная работа продолжается.
- 403: не повторять бесконечно.
- 409/conflict: передать в conflict UI.
- 422: сохранить ошибку и предложить исправить данные.
- 5xx: повторить с тем же mutation_id.
- Один Sync Engine на аккаунт, без параллельных циклов.

## 17. Обязательные тесты

1. Create офлайн, process death, restart, успешный push.
2. Таймаут после серверного commit и повтор той же mutation.
3. Несколько локальных update объединяются без ложного конфликта.
4. Create + delete до первой синхронизации не создаёт серверную сущность.
5. Два устройства меняют одно поле: второе получает конфликт.
6. Два устройства меняют разные вещи: обе операции применяются.
7. Pull страницы прерывается посередине; повтор не теряет seq.
8. Pending entity не перезаписывается pull.
9. Web update появляется на телефоне.
10. Tombstone доходит на второе устройство.
11. Фотография загружается после карточки.
12. Ошибка фотографии не блокирует другие фотографии и вещи.
13. Пользователь B не может выполнить push или pull для данных A.
14. Истёкший токен не очищает локальную БД.
15. Logout с pending-данными требует подтверждения.
16. Новый клиент выполняет начальную синхронизацию с since=0.
17. Категория, вещь и фото, созданные офлайн, сходятся в правильном порядке.
18. Повторный upload готового photo_id не создаёт дубликат.

## 18. Инварианты, которые нельзя нарушать

- Нет изменения серверной сущности без журнала.
- Нет обновления last_pulled_seq без сохранения соответствующих данных.
- Нет потери outbox при обновлении UI или истечении сессии.
- Нет молчаливого last-write-wins по времени телефона.
- Нет доверия user_id из клиентского payload.
- Нет удаления журнала только по возрасту.
- Нет автоматической перезаписи конфликтующей локальной версии.

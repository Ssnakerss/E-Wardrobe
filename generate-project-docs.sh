## 12. Нефункциональные требования

- Все серверные timestamps хранятся как timestamptz в UTC.
- Дата последней носки хранится как date.
- Все внешние запросы имеют timeout.
- Изменяющие HTTP-запросы не должны зависать при недоступном файловом хранилище.
- Backend запускается одним экземпляром.
- Миграции запускаются до переключения на новую версию backend.
- Логи не содержат пароли, токены, приглашения и содержимое фотографий.
- Бэкап включает PostgreSQL и файлы фотографий.
- Перед релизом выполняется тестовое восстановление.
- Списки не загружают полный гардероб одним HTTP-запросом.
- Мобильный список использует локальную пагинацию или виртуализацию.

## 13. Что не входит в MVP

- Открытая самостоятельная регистрация.
- Полноценная offline-версия веб-клиента.
- Подтверждение email и автоматическая отправка писем.
- Социальный вход.
- Подбор образов и комплектов.
- История каждой носки; хранится только последняя дата.
- Напоминания о стирке и химчистке.
- Распознавание одежды через ИИ.
- Публичные гардеробы и совместный доступ.
- Курсы валют и конвертация.
- Иерархический справочник мест хранения.
- S3, Redis, очередь сообщений и микросервисы.
- Гарантированная фоновая синхронизация мобильных ОС.


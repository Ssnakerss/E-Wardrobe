# Wardrobe — требования и пошаговый план MVP

Статус: baseline v0.1  
Назначение: зафиксировать объём первой production-версии и критерии её готовности.

## 1. Цель продукта

Система помогает пользователю помнить, какие личные вещи у него есть, где они хранятся и в каком состоянии находятся.

Основной сценарий:

1. Пользователь фотографирует вещь на телефон.
2. Добавляет название, категорию и необязательные характеристики.
3. Сохраняет вещь даже без подключения к сети.
4. Позже находит её через поиск, категории и фильтры.
5. После синхронизации видит те же данные в веб-клиенте и на других устройствах.

## 2. Участники

- Пользователь — владелец своего гардероба.
- Оператор установки — администрирует Docker-окружение и создаёт приглашения через CLI.

Отдельной роли администратора внутри веб-приложения в MVP нет.

## 3. Платформы и компоненты

- Мобильное приложение: React Native, Expo, TypeScript, Android и iOS.
- Локальная мобильная БД: SQLite.
- Backend: Go, модульный монолит.
- Основная БД: PostgreSQL.
- Веб-клиент: HTML, CSS, TypeScript без UI-фреймворка.
- Веб-сборка встраивается в Go-бинарник и раздаётся backend.
- Фотографии: файловое хранилище на Docker volume за абстракцией PhotoStorage.
- Развёртывание: Docker Compose, Caddy, API и PostgreSQL.

Веб-клиент является полноценным онлайн-клиентом. Offline-first реализуется на мобильном приложении.

## 4. Регистрация и доступ

Регистрация возможна только по одноразовому приглашению.

Требования:

- Приглашение создаётся командой оператора.
- Ссылка может быть передана пользователю вручную.
- SMTP и отправка email в MVP не требуются.
- Срок действия приглашения по умолчанию — 7 суток.
- Приглашение может быть привязано к email.
- В базе хранится только хеш токена приглашения.
- Использованное, просроченное или отозванное приглашение не принимается.
- Регистрация и погашение приглашения происходят в одной транзакции.
- После регистрации пользователю копируется базовый справочник категорий.
- Повторное использование ссылки запрещено.
- Вход, регистрация и проверка приглашения защищаются rate limiting.

Пример команды:

    docker compose exec api wardrobe invite create \
      --email user@example.com \
      --expires 168h

Доступ к данным:

- Пользователь видит только свои категории, вещи и фотографии.
- Проверка владельца выполняется на backend для каждого запроса.
- Знание UUID чужой сущности не даёт доступа к ней.
- URL фотографий не являются публичными.

## 5. Аутентификация

Используются серверные сессии с непрозрачными случайными токенами.

Веб:

- Session ID передаётся в HttpOnly Secure cookie.
- SameSite и проверка Origin ограничивают межсайтовые запросы.
- Изменяющие запросы дополнительно защищаются CSRF-токеном.
- JavaScript не получает серверный session token.

Мобильное приложение:

- Получает Bearer token после входа или регистрации.
- Хранит его в iOS Keychain или Android Keystore через Secure Store.
- Истечение серверной сессии не блокирует доступ к локальной SQLite БД.
- После повторной аутентификации можно продолжить синхронизацию.

Пароли хешируются Argon2id. Восстановление доступа в MVP выполняется через одноразовую recovery-ссылку, созданную оператором через CLI. Автоматическая отправка писем не входит в объём.

## 6. Категории

Категории образуют дерево произвольной разумной глубины.

Пример базового шаблона:

    Одежда
      Верхняя одежда
      Футболки
        Спортивные
      Брюки
      Нижнее бельё
    Обувь
      Зимняя
      Летняя
      Спортивная
    Аксессуары
    Прочее

Правила:

- Базовый шаблон хранится в backend.
- При регистрации шаблон копируется в категории пользователя.
- template_key сохраняет связь с исходным элементом шаблона.
- После копирования категории принадлежат пользователю и синхронизируются обычным образом.
- Пользователь может создавать, переименовывать, перемещать и архивировать категории.
- Перемещение не должно создавать цикл.
- Родительская категория должна принадлежать тому же пользователю.
- Нельзя окончательно удалить категорию, если на неё ссылаются активные вещи или дочерние категории.
- В такой ситуации предлагается архивирование либо предварительное перемещение вещей.

